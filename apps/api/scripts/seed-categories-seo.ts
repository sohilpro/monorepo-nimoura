function normalizeFa(text: string): string {
  return text.replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/\s+/g, ' ').trim();
}

function findCuratedEntry(cat: Categories): CategorySeoEntry | undefined {
  const nameKey = normalizeFa(cat.name);
  if (CURATED_CATEGORY_SEO[nameKey]) {
    return CURATED_CATEGORY_SEO[nameKey];
  }
  const catSlug = slugify(cat.slug || nameKey);
  for (const [k, entry] of Object.entries(CURATED_CATEGORY_SEO)) {
    const normK = normalizeFa(k);
    if (slugify(normK) === catSlug || generateSlug(normK) === cat.slug) {
      return entry;
    }
  }
  return undefined;
}

export async function seed(ds: DataSource): Promise<void> {
  const force = process.argv.includes('--force');

  await ds.transaction(async (manager) => {
    const repo = manager.getRepository(Categories);
    const categories = await repo.find({
      relations: { parent: true, children: true },
      order: { id: 'ASC' },
      loadEagerRelations: false,
    });

    if (!categories.length) {
      console.log('هیچ دسته‌بندی فعالی در دیتابیس پیدا نشد.');
      return;
    }

    const usedSlugs = new Set<string>(
      categories.map((c) => c.slug).filter((s): s is string => !!s?.trim()),
    );

    let updatedCount = 0;
    let skippedCount = 0;

    for (const cat of categories) {
      const seo = findCuratedEntry(cat) ?? buildFallbackSeo(cat);
      let changed = false;

      if (!cat.slug || !cat.slug.trim()) {
        const base = generateSlug(cat.name) || slugify(cat.name) || `cat-${cat.id}`;
        let candidate = base;
        let idx = 2;
        while (usedSlugs.has(candidate)) {
          candidate = `${base}-${idx++}`;
        }
        cat.slug = candidate;
        usedSlugs.add(candidate);
        changed = true;
      }

      if (force || !cat.seoTitle?.trim()) {
        cat.seoTitle = seo.seoTitle;
        changed = true;
      }

      if (force || !cat.seoDescription?.trim()) {
        cat.seoDescription = seo.seoDescription;
        changed = true;
      }

      if (force || !cat.seoText?.trim()) {
        cat.seoText = seo.seoText;
        changed = true;
      }

      if (changed) {
        await repo.save(cat);
        updatedCount += 1;
        console.log(`  ~ سئو دسته‌بندی به‌روزرسانی شد: ${cat.name} (id=${cat.id}, slug=${cat.slug})`);
      } else {
        skippedCount += 1;
        console.log(`  = بدون تغییر (سئو از قبل پر بود): ${cat.name} (id=${cat.id})`);
      }
    }

    console.log(
      `\n✓ پردازش ${categories.length} دسته‌بندی انجام شد | به‌روزرسانی‌شده: ${updatedCount} | ردشده: ${skippedCount}`,
    );
  });
}

if (require.main === module) {
  runStandaloneSeed('Category SEO Content', seed);
}
